import requests
import json
import os
import sys
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

from concurrent.futures import ThreadPoolExecutor

BASE_URL = "http://127.0.0.1:5000"
BATCH_ID = 285
OUTPUT_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "Batch_285_Lectures_Full_HD.txt")

def to_youtube_watch(url):
    if not url:
        return ""
    if "/embed/" in url:
        return url.replace("/embed/", "/watch?v=")
    return url


def export_hd_batch():
    print(f"[EXPORT] Generating Full HD (1080p/720p) Batch {BATCH_ID}...")

    # 1. Get Batch Info
    batch_title = f"Batch {BATCH_ID}"
    try:
        r_batches = requests.get(f"{BASE_URL}/api/batches", timeout=10)
        if r_batches.status_code == 200:
            for b in r_batches.json():
                if str(b.get("id")) == str(BATCH_ID):
                    batch_title = b.get("title") or batch_title
                    break
    except Exception:
        pass

    # 2. Get Classroom Topics
    r_class = requests.get(f"{BASE_URL}/api/classroom/{BATCH_ID}", timeout=15)
    topics = r_class.json().get("classroom", [])
    print(f"[INFO] Batch '{batch_title}' has {len(topics)} topics.")

    all_lectures = []
    all_notes = []
    session = requests.Session()

    for t_idx, topic in enumerate(topics, 1):
        topic_id = topic.get("id")
        topic_name = topic.get("name") or topic.get("title") or f"Topic {topic_id}"

        try:
            r_lesson = session.get(f"{BASE_URL}/api/lesson/{topic_id}", timeout=15)
            if r_lesson.status_code != 200:
                continue

            ldata = r_lesson.json()
            raw_videos = ldata.get("videos", [])
            raw_notes = ldata.get("notes", [])
            raw_videos_sorted = list(reversed(raw_videos)) if raw_videos else []

            def resolve_video(v):
                vid = v.get("id")
                v_name = (v.get("name") or v.get("title") or f"Lecture {vid}").strip()
                try:
                    rv = session.get(f"{BASE_URL}/api/video/{vid}", timeout=8)
                    if rv.status_code == 200:
                        vd = rv.json()
                        hd_url = vd.get("hd_video_url") or ""
                        sd_url = vd.get("video_url") or ""
                        pdfs = vd.get("pdfs") or []
                        return (v_name, hd_url, sd_url, pdfs)
                except Exception:
                    pass
                return (v_name, "", "", [])

            with ThreadPoolExecutor(max_workers=10) as executor:
                results = list(executor.map(resolve_video, raw_videos_sorted))

            for v_name, hd_url, sd_url, pdfs in results:
                # Prefer HD URL (1080p YouTube), fallback to SD
                best_url = to_youtube_watch(hd_url) if hd_url else sd_url
                if best_url:
                    all_lectures.append({
                        "topic": topic_name,
                        "title": v_name,
                        "hd_url": to_youtube_watch(hd_url),
                        "sd_url": sd_url,
                        "best_url": best_url
                    })
                for p in pdfs:
                    if p.get("url"):
                        all_notes.append({
                            "topic": topic_name,
                            "title": p.get("title") or v_name,
                            "url": p.get("url")
                        })

            for n in raw_notes:
                if n.get("url"):
                    all_notes.append({
                        "topic": topic_name,
                        "title": (n.get("name") or n.get("title") or "Note").strip(),
                        "url": n.get("url")
                    })

        except Exception as e:
            print(f"Error on topic {topic_id}: {e}")

    lines = []
    lines.append("=" * 70)
    lines.append(f"Batch Name: {batch_title}")
    lines.append(f"Batch ID: {BATCH_ID}")
    lines.append(f"Quality Mode: FULL HD (1080p / 720p YouTube Streams + MP4 Fallback)")
    lines.append(f"Total Video Lectures: {len(all_lectures)}")
    lines.append(f"Total PDF Notes: {len(all_notes)}")
    lines.append("Generated by: StudyMate Resilient API (http://localhost:5000)")
    lines.append("=" * 70)
    lines.append("\n--- FULL HD VIDEO LECTURES ---\n")

    current_topic = None
    for idx, lec in enumerate(all_lectures, 1):
        if lec["topic"] != current_topic:
            current_topic = lec["topic"]
            lines.append(f"\n[Topic: {current_topic}]")
        
        # Output clean link with highest available quality
        lines.append(f"{idx:03d}. {lec['title']}: {lec['best_url']}")

    if all_notes:
        lines.append("\n\n" + "=" * 70)
        lines.append("--- PDF STUDY NOTES ---")
        lines.append("=" * 70 + "\n")
        current_topic = None
        for idx, note in enumerate(all_notes, 1):
            if note["topic"] != current_topic:
                current_topic = note["topic"]
                lines.append(f"\n[Topic: {current_topic}]")
            lines.append(f"{idx:03d}. {note['title']}: {note['url']}")

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"[SUCCESS] Full HD file written to: {OUTPUT_FILE}")
    print(f"File Size: {os.path.getsize(OUTPUT_FILE)} bytes")

if __name__ == "__main__":
    export_hd_batch()
