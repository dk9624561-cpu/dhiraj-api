import requests
import json
import os
import sys
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

from concurrent.futures import ThreadPoolExecutor, as_completed

BASE_URL = "http://127.0.0.1:5000"
BATCH_ID = 285
OUTPUT_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "Batch_285_Lectures.txt")



def export_batch():
    print(f"[EXPORT] Fetching Batch {BATCH_ID} from Localhost API ({BASE_URL})...")

    # 1. Get Batch Info
    batch_title = f"Batch {BATCH_ID}"
    try:
        r_batches = requests.get(f"{BASE_URL}/api/batches", timeout=10)
        if r_batches.status_code == 200:
            for b in r_batches.json():
                if str(b.get("id")) == str(BATCH_ID):
                    batch_title = b.get("title") or batch_title
                    break
    except Exception as e:
        print(f"Warning fetching batch title: {e}")

    # 2. Get Classroom Topics
    r_class = requests.get(f"{BASE_URL}/api/classroom/{BATCH_ID}", timeout=15)
    if r_class.status_code != 200:
        print(f"[ERROR] Failed to fetch classroom: {r_class.status_code}")
        return

    topics = r_class.json().get("classroom", [])
    print(f"[INFO] Batch '{batch_title}' has {len(topics)} topics.")

    all_lectures = []
    all_notes = []

    # 3. Fetch lessons for each topic in order
    session = requests.Session()

    for t_idx, topic in enumerate(topics, 1):
        topic_id = topic.get("id")
        topic_name = topic.get("name") or topic.get("title") or f"Topic {topic_id}"
        print(f" -> [{t_idx}/{len(topics)}] Fetching Topic {topic_id}: {topic_name}...")

        try:
            r_lesson = session.get(f"{BASE_URL}/api/lesson/{topic_id}", timeout=15)
            if r_lesson.status_code != 200:
                continue

            ldata = r_lesson.json()
            raw_videos = ldata.get("videos", [])
            raw_notes = ldata.get("notes", [])

            # Reverse chronological to chronological if needed
            # Videos usually in reverse order (e.g., lecture 31 down to lecture 1)
            raw_videos_sorted = list(reversed(raw_videos)) if raw_videos else []

            # Resolve video URLs using thread pool for speed
            def resolve_video(v):
                vid = v.get("id")
                v_name = (v.get("name") or v.get("title") or f"Lecture {vid}").strip()
                try:
                    rv = session.get(f"{BASE_URL}/api/video/{vid}", timeout=10)
                    if rv.status_code == 200:
                        vd = rv.json()
                        v_url = vd.get("video_url") or vd.get("hd_video_url") or ""
                        pdfs = vd.get("pdfs") or []
                        return (v_name, v_url, pdfs)
                except Exception:
                    pass
                return (v_name, "", [])

            with ThreadPoolExecutor(max_workers=8) as executor:
                results = list(executor.map(resolve_video, raw_videos_sorted))

            for v_name, v_url, pdfs in results:
                if v_url:
                    all_lectures.append({
                        "topic": topic_name,
                        "title": v_name,
                        "url": v_url
                    })
                for p in pdfs:
                    p_url = p.get("url")
                    p_title = p.get("title") or v_name
                    if p_url:
                        all_notes.append({
                            "topic": topic_name,
                            "title": p_title,
                            "url": p_url
                        })

            for n in raw_notes:
                n_url = n.get("url")
                n_title = (n.get("name") or n.get("title") or "Note").strip()
                if n_url:
                    all_notes.append({
                        "topic": topic_name,
                        "title": n_title,
                        "url": n_url
                    })

        except Exception as e:
            print(f"Error processing topic {topic_id}: {e}")

    # 4. Generate formatted TXT output
    print(f"\n[DONE] Successfully resolved {len(all_lectures)} video lectures & {len(all_notes)} PDF notes!")

    lines = []
    lines.append("=" * 70)
    lines.append(f"Batch Name: {batch_title}")
    lines.append(f"Batch ID: {BATCH_ID}")
    lines.append(f"Total Video Lectures: {len(all_lectures)}")
    lines.append(f"Total PDF Notes: {len(all_notes)}")
    lines.append("Generated by: StudyMate Resilient API (http://localhost:5000)")
    lines.append("=" * 70)
    lines.append("\n--- VIDEO LECTURES ---\n")

    current_topic = None
    for idx, lec in enumerate(all_lectures, 1):
        if lec["topic"] != current_topic:
            current_topic = lec["topic"]
            lines.append(f"\n[Topic: {current_topic}]")
        
        # Ensure clean numbering 001. 002. etc.
        lines.append(f"{idx:03d}. {lec['title']}: {lec['url']}")

    if all_notes:
        lines.append("\n\n" + "=" * 70)
        lines.append("--- PDF STUDY NOTES ---")
        lines.append("=" * 70 + "\n")
        current_topic = None
        for idx, note in enumerate(all_notes, 1):
            if note["topic"] != current_topic:
                current_topic = note["topic"]
                lines.append(f"\n[Topic: {current_topic}]")
            lines.append(f"{idx:03d}. {note['title']}: {note['url']}")

    txt_content = "\n".join(lines)

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(txt_content)

    print(f"[SAVED] Batch TXT file written to:\n  {OUTPUT_FILE}")
    print(f"File Size: {os.path.getsize(OUTPUT_FILE)} bytes")

if __name__ == "__main__":
    export_batch()
